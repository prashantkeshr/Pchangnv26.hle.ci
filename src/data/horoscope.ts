export function getDailyInsight(rashi: Rashi, date: Date): { career: string; health: string; love: string; finance: string; overall: number } {
  const seed = date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
  const rashiIdx = RASHIS.indexOf(rashi);
  const careerOptions = [
    'Focus on collaborative projects today. Teamwork brings unexpected rewards.',
    'An opportunity for professional growth may present itself. Stay alert.',
    'Complete pending tasks before starting new ones. Discipline is key today.',
    'Your leadership skills will be tested. Rise to the challenge with confidence.',
    'Networking will prove beneficial. Reconnect with former colleagues.',
    'A creative approach to a work problem will impress superiors.',
  ];

  const healthOptions = [
    'Practice yoga or meditation to maintain mental balance.',
    'Maintain a balanced diet and avoid late-night meals.',
    'Morning walks or exercise will boost your energy levels.',
    'Pay attention to hydration and adequate rest today.',
    'Stress management is important. Take short breaks throughout the day.',
    'Pranayama and deep breathing will help maintain vitality.',
  ];

  const loveOptions = [
    'Open communication strengthens bonds with loved ones.',
    'A surprise gesture for your partner will deepen your relationship.',
    'Single natives may encounter an interesting person today.',
    'Family time brings joy and harmony. Plan an outing together.',
    'Express your feelings honestly. Vulnerability builds stronger connections.',
    'Patience with your partner will resolve any misunderstandings.',
  ];

  const financeOptions = [
    'Avoid impulsive purchases. Review your budget carefully.',
    'A good day for long-term investments and financial planning.',
    'An unexpected financial gain is possible. Save wisely.',
    'Review subscriptions and recurring expenses for potential savings.',
    'Consult before making major financial decisions today.',
    'Focus on clearing debts rather than making new investments.',
  ];

  const pick = (n: number, len: number) => {
    const v = ((seed * 7 + rashiIdx * 13 + n * 31) % 9973);
    return v % len;
  };

  return {
    career: careerOptions[pick(1, careerOptions.length)]!,
    health: healthOptions[pick(2, healthOptions.length)]!,
    love: loveOptions[pick(3, loveOptions.length)]!,
    finance: financeOptions[pick(4, financeOptions.length)]!,
    overall: (pick(5, 5)) + 1,
  };
}
